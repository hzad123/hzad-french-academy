// Generate an auditable immutable owner-approved v5 release migration.
// The only waived requirement is the blind guessing-rate target; all exact
// bank keys, source recordings, durations and protected history are checked.
import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {publicationSQL6} from './listening-01-06-v4.mjs';
import {strictProtectedTables} from './listening-owner-review.mjs';

const out=process.argv[2];
if(!/^supabase\/migrations\/\d+_tcf_listening_01_06_owner_waiver_v5\.sql$/.test(out||''))
  throw Error('Use a migration path generated by Supabase CLI: tcf_listening_01_06_owner_waiver_v5');
const papers=[];
for(let number=1;number<=6;number++){
 const label=String(number).padStart(2,'0'),path='supabase/exams/tcf-listening-test'+label+'-v5.json';
 const paper=JSON.parse(await readFile(path,'utf8'));
 execFileSync('node',['scripts/check-listening-owner-waiver-v5.mjs','--bank',path,
  '--evidence','curriculum/tcf-listening-owner-waiver-v5/'+paper.version,'--media'],{stdio:'inherit'});
 papers.push(paper);
}
let sql=publicationSQL6(papers,strictProtectedTables,{revision:5});
const before='-- Strict Listening01–06 v5: independent blind, transcript, paper and late-cohort gates passed.\n-- All234 keys were independently grounded; verified media must be deployed first.\n-- Historical banks, attempts, clocks, scoring and access remain immutable.';
const after='-- OWNER-APPROVED TCF Listening01-06 v5: blind-guessing threshold expressly waived on 19 November 2026.\n-- Every key retains independent transcript/image grounding; any unapproved edited question falls back to published verified v4.\n-- All 234 source-matched audio clips and original images must be live and verified before activation.\n-- Historical attempts, banks, clocks, scoring, wallet, access and TEF records remain protected by transaction hashes.';
if(!sql.startsWith(before))throw Error('Base publication generator changed; re-review required');
sql=sql.replace(before,after);
await writeFile(out,sql);
console.log('Generated reviewed six-paper owner-waiver v5 migration; verify exact hosted assets before applying it.');
